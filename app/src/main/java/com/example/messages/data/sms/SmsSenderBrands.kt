import androidx.annotation.DrawableRes
import com.example.messages.R
import java.util.Locale

internal data class SmsSenderBrand(val name: String, @DrawableRes val logo: Int)

private val senderId = Regex("""(?:[A-Za-z]{2}-)?([A-Za-z0-9]{3,11})(?:-[PGSTpgst])?""")
private val headerSeparator = Regex("""\s+""")

internal fun smsSenderBrand(address: String): SmsSenderBrand? {
    val header = senderId.matchEntire(address.trim())?.groupValues?.get(1) ?: return null
    return brandsByHeader[header.uppercase(Locale.ROOT)]
}

private fun MutableMap<String, SmsSenderBrand>.register(name: String, @DrawableRes logo: Int, headers: String) {
    val brand = SmsSenderBrand(name, logo)
    headers.trim().split(headerSeparator).forEach { header -> put(header, brand) }
}

